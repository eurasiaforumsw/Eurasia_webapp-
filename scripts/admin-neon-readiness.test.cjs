function binding(expression, values) {
  const match = expression.trim().match(/^\$(\d+)(?:::.*)?$/);
  if (match) return values[Number(match[1]) - 1];
  if (expression === 'true') return true;
  if (expression === 'false') return false;
  assert.fail(`Unexpected value ${expression}`);
}
function matches(row, where, values) {
  if (!where) return true;
  return where.split(' AND ').every((raw) => {
    const part = raw.trim().replace(/^\((.*)\)$/, '$1');
    let match = part.match(/^(\w+) (?:= ANY\((\$\d+)\)|IN \(([^)]+)\))$/);
    if (match) return (match[2] ? binding(match[2], values) : match[3].split(',').map((val) => binding(val, values))).includes(row[match[1]]);
    match = part.match(/^(\w+) @> ARRAY\[(\$\d+)\]::text\[\]$/);
    if (match) return row[match[1]]?.includes(binding(match[2], values));
    match = part.match(/^(\w+) (>=|<=|>|<|=) (\$\d+|true|false)$/);
    assert.ok(match, `Unexpected predicate ${part}`);
    const value = binding(match[3], values);
    const left = row[match[1]] instanceof Date ? row[match[1]].toISOString() : row[match[1]];
    return match[2] === '=' ? left === value : match[2] === '>=' ? left >= value : match[2] === '<=' ? left <= value : match[2] === '>' ? left > value : left < value;
  });
}
function isFlagged(content) { return (content.match(/[A-Z]/g) || []).length / content.length > 0.7 || /[!?]{3,}/.test(content) || /(.)\1{4,}/.test(content) || content.trim().length < 5; }
function messageMatches(row, sql, values) {
  if (row.deleted_at) return false;
  const where = sql.split(' WHERE ')[1]?.split(' ORDER BY ')[0] || '';
  if (where.includes("m.content ~* 'https?://'" ) && !/https?:\/\//i.test(row.content)) return false;
  if (where.includes('LENGTH(REGEXP_REPLACE') && !isFlagged(row.content)) return false;
  for (const match of where.matchAll(/m\.(content|created_at) (ILIKE|>=|<=) \$(\d+)/g)) {
    const value = values[Number(match[3]) - 1];
    if (match[2] === 'ILIKE' && !row.content.toLowerCase().includes(value.slice(1, -1).toLowerCase())) return false;
    if (match[2] === '>=' && row.created_at < value) return false;
    if (match[2] === '<=' && row.created_at > value) return false;
  }
  return true;
}
